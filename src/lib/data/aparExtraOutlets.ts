function slugifyOutletName(name: string): string {
  return name
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

const seenSlugs = new Set<string>();

export const APAR_EXTRA_OUTLETS: Outlet[] = APAR_EXTRA_OUTLET_NAMES.reduce<Outlet[]>(
  (acc, rawName) => {
    const cleanName = rawName.trim().toUpperCase();
    const slug = slugifyOutletName(cleanName);
    if (!cleanName || !slug || seenSlugs.has(slug)) return acc;
    seenSlugs.add(slug);
    acc.push({
      id: `apar-extra-${slug}`,
      name: cleanName,
      areaId: '', // Belum masuk area (khusus APAR)
      targetHead: 0,
      umr: 0,
      class: 'C',
      address: '',
      studios: [],
    });
    return acc;
  },
  []
);
